"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { ClipboardCheck, Plus, Sparkles, Trash2 } from "lucide-react";
import { useState } from "react";
import { Button, Card, Input, Table, Textarea } from "@/components/ui";
import { formatDate, formatMs, formatPercent, parseList } from "@/lib/rag/format";
import { ragApi, type EvaluationCase, type EvaluationRun } from "@/lib/rag/api";
import { DocumentPicker } from "./DocumentPicker";
import {
  ErrorNotice,
  KeyValue,
  Loading,
  Mono,
  Notice,
  SectionHeading,
  Stat,
  StatusBadge,
  WarningList,
} from "./shared";

const EMPTY_CASE: EvaluationCase = {
  question: "",
  expected_keywords: [],
  expected_chunk_ids: [],
};

export function EvaluationPanel() {
  const queryClient = useQueryClient();
  const datasets = useQuery({ queryKey: ["evaluation-datasets"], queryFn: ragApi.datasets });
  const history = useQuery({ queryKey: ["evaluation-history"], queryFn: () => ragApi.evaluationHistory(10) });

  const [dataset, setDataset] = useState("custom");
  const [documentIds, setDocumentIds] = useState<string[]>([]);
  const [cases, setCases] = useState<EvaluationCase[]>([]);
  const [topK, setTopK] = useState(6);
  const [minimumSimilarity, setMinimumSimilarity] = useState(0.25);
  const [generate, setGenerate] = useState(false);

  const suggest = useMutation({ mutationFn: (documentId: string) => ragApi.suggestCases(documentId, 5) });
  const run = useMutation({
    mutationFn: ragApi.runEvaluation,
    onSuccess: async () => {
      await queryClient.invalidateQueries({ queryKey: ["evaluation-history"] });
      await queryClient.invalidateQueries({ queryKey: ["overview"] });
    },
  });

  const addCase = () => setCases((current) => [...current, { ...EMPTY_CASE }]);
  const updateCase = (index: number, patch: Partial<EvaluationCase>) =>
    setCases((current) => current.map((item, itemIndex) => (itemIndex === index ? { ...item, ...patch } : item)));
  const removeCase = (index: number) =>
    setCases((current) => current.filter((_, itemIndex) => itemIndex !== index));

  const suggestionDocument = documentIds[0];

  const onSuggest = () => {
    if (!suggestionDocument) return;
    suggest.mutate(suggestionDocument, {
      onSuccess: (suggestions) => {
        setCases((current) => [
          ...current,
          ...suggestions.map((suggestion) => ({
            ...suggestion.case,
            notes: suggestion.case.notes ?? suggestion.rationale,
          })),
        ]);
      },
    });
  };

  const invalidCases = cases.filter(
    (item) => !item.question.trim() || (!item.expected_keywords.length && !item.expected_chunk_ids.length),
  );

  const onRun = () => {
    run.mutate({
      dataset_id: dataset,
      document_ids: documentIds,
      cases,
      top_k: topK,
      minimum_similarity: minimumSimilarity,
      generate,
    });
  };

  return (
    <div className="space-y-6">
      <SectionHeading
        eyebrow="Engineering console"
        title="Evaluation lab"
        detail="Cases need expected keywords or chunk IDs. Suggested cases are derived deterministically from persisted chunks, not generated by a model."
      />

      <div className="grid gap-4 lg:grid-cols-[0.9fr_1.1fr]">
        <Card className="space-y-4 p-5">
          <label className="block">
            <span className="eyebrow">Dataset</span>
            <select
              className="mt-1.5 h-9 w-full rounded-sm border border-line bg-surface px-3 text-sm text-ink outline-none focus:border-accent"
              value={dataset}
              onChange={(event) => setDataset(event.target.value)}
            >
              {datasets.data?.map((item) => (
                <option key={item.id} value={item.id}>
                  {item.name}
                </option>
              ))}
              <option value="custom">Custom cases</option>
            </select>
            {datasets.data?.find((item) => item.id === dataset)?.description ? (
              <span className="mt-1 block text-[11px] text-muted">
                {datasets.data.find((item) => item.id === dataset)?.description}
              </span>
            ) : null}
          </label>

          <DocumentPicker
            value={documentIds}
            onChange={setDocumentIds}
            label="Evaluate against"
            hint="Use one document for suggested cases; multiple are allowed for custom cases."
          />

          <div className="grid grid-cols-2 gap-3">
            <label className="block">
              <span className="eyebrow">Top K</span>
              <Input type="number" min={1} max={20} value={topK} onChange={(event) => setTopK(Number(event.target.value))} />
            </label>
            <label className="block">
              <span className="eyebrow">Min similarity</span>
              <Input
                type="number"
                min={0}
                max={1}
                step={0.05}
                value={minimumSimilarity}
                onChange={(event) => setMinimumSimilarity(Number(event.target.value))}
              />
            </label>
          </div>

          <label className="flex items-center gap-2 text-sm">
            <input type="checkbox" checked={generate} onChange={(event) => setGenerate(event.target.checked)} />
            Also run generation and citation checks
          </label>

          <div className="flex flex-wrap gap-2">
            <Button variant="secondary" onClick={addCase}>
              <Plus aria-hidden className="size-4" /> Add case
            </Button>
            <Button
              variant="secondary"
              onClick={onSuggest}
              disabled={!suggestionDocument || suggest.isPending}
            >
              <Sparkles aria-hidden className="size-4" /> Suggest from chunks
            </Button>
            <Button
              onClick={onRun}
              disabled={!cases.length || invalidCases.length > 0 || run.isPending}
            >
              <ClipboardCheck aria-hidden className="size-4" /> Run evaluation
            </Button>
          </div>
          {suggest.error ? <ErrorNotice error={suggest.error} /> : null}
          {run.error ? <ErrorNotice error={run.error} /> : null}
          {cases.length > 0 && invalidCases.length > 0 ? (
            <Notice tone="warning">
              {invalidCases.length} case{invalidCases.length === 1 ? "" : "s"} need a question and at least
              one expected keyword or chunk ID.
            </Notice>
          ) : null}
        </Card>

        <Card className="p-5">
          <h3 className="section-title">Metric definitions</h3>
          <dl className="mt-4">
            <KeyValue label="Hit rate" value="share of cases with relevant evidence in top K" />
            <KeyValue label="MRR" value="mean reciprocal rank of first relevant source" />
            <KeyValue label="Answer rate" value="share of cases with a non-insufficient status" />
            <KeyValue label="Grounded rate" value="grounded answers ÷ answered cases" />
            <KeyValue label="Citation coverage" value="answered cases with ≥1 citation" />
          </dl>
          <div className="mt-4">
            <Notice tone="info">
              Relevance is checked against your expected keywords or chunk IDs. A hit means the evidence
              appeared in the retrieved sources, not that a model judged the answer.
            </Notice>
          </div>
        </Card>
      </div>

      <Card className="overflow-hidden">
        <div className="border-b px-5 py-4">
          <h3 className="section-title">Cases</h3>
          <p className="mt-0.5 text-xs text-muted">Comma-separated keywords and chunk IDs.</p>
        </div>
        {cases.length === 0 ? (
          <p className="px-5 py-8 text-sm text-muted">
            No cases yet. Add one manually or suggest cases from a document&apos;s persisted chunks.
          </p>
        ) : (
          <div className="space-y-3 p-4">
            {cases.map((item, index) => (
              <div key={index} className="rounded-sm border p-3">
                <div className="flex items-start gap-2">
                  <span className="mt-2 font-mono text-[11px] text-muted">{index + 1}</span>
                  <div className="grid flex-1 gap-2">
                    <Textarea
                      className="min-h-16"
                      placeholder="Question"
                      value={item.question}
                      onChange={(event) => updateCase(index, { question: event.target.value })}
                    />
                    <div className="grid gap-2 sm:grid-cols-2">
                      <Input
                        placeholder="expected keywords, comma separated"
                        value={item.expected_keywords.join(", ")}
                        onChange={(event) =>
                          updateCase(index, { expected_keywords: parseList(event.target.value) })
                        }
                      />
                      <Input
                        placeholder="expected chunk IDs, comma separated"
                        value={item.expected_chunk_ids.join(", ")}
                        onChange={(event) =>
                          updateCase(index, { expected_chunk_ids: parseList(event.target.value) })
                        }
                      />
                    </div>
                    {item.notes ? <p className="text-[11px] text-muted">{item.notes}</p> : null}
                  </div>
                  <Button variant="ghost" size="sm" onClick={() => removeCase(index)} aria-label="Remove case">
                    <Trash2 aria-hidden className="size-3.5" />
                  </Button>
                </div>
              </div>
            ))}
          </div>
        )}
      </Card>

      {run.isPending ? <Loading label="Running evaluation" /> : null}
      {run.data ? <RunResult run={run.data} /> : null}

      <Card className="overflow-hidden">
        <div className="border-b px-5 py-4">
          <h3 className="section-title">History</h3>
        </div>
        {history.isLoading ? (
          <Loading label="Loading history" />
        ) : history.error ? (
          <div className="p-5"><ErrorNotice error={history.error} /></div>
        ) : !history.data?.runs.length ? (
          <p className="px-5 py-8 text-sm text-muted">No evaluation runs yet.</p>
        ) : (
          <Table>
            <thead className="border-b border-line/70">
              <tr>
                <th className="px-4 py-2 font-medium">Dataset</th>
                <th className="px-4 py-2 font-medium">Hit rate</th>
                <th className="px-4 py-2 font-medium">MRR</th>
                <th className="px-4 py-2 font-medium">Cases</th>
                <th className="px-4 py-2 font-medium">Duration</th>
                <th className="px-4 py-2 font-medium">When</th>
              </tr>
            </thead>
            <tbody>
              {history.data.runs.map((item) => (
                <tr key={item.id} className="border-t border-line/70">
                  <td className="px-4 py-2">{item.dataset_id}</td>
                  <td className="px-4 py-2 font-mono text-xs">{formatPercent(item.metrics.retrieval_hit_rate)}</td>
                  <td className="px-4 py-2 font-mono text-xs">{item.metrics.mrr.toFixed(4)}</td>
                  <td className="px-4 py-2 font-mono text-xs">{item.metrics.cases}</td>
                  <td className="px-4 py-2 font-mono text-xs">{formatMs(item.duration_ms)}</td>
                  <td className="px-4 py-2 text-xs text-muted">{formatDate(item.created_at)}</td>
                </tr>
              ))}
            </tbody>
          </Table>
        )}
      </Card>
    </div>
  );
}

function RunResult({ run }: { run: EvaluationRun }) {
  return (
    <div className="space-y-4">
      <div className="grid gap-x-8 gap-y-8 sm:grid-cols-3 lg:grid-cols-6">
        <Stat label="Hit rate" value={formatPercent(run.metrics.retrieval_hit_rate)} hint={`${run.metrics.hits} / ${run.metrics.cases}`} tone={run.metrics.retrieval_hit_rate >= 0.8 ? "success" : "warning"} />
        <Stat label="MRR" value={run.metrics.mrr.toFixed(4)} hint="mean reciprocal rank" />
        <Stat label="Answer rate" value={formatPercent(run.metrics.answer_rate)} hint="non-insufficient" />
        <Stat label="Grounded" value={formatPercent(run.metrics.grounded_rate)} hint="of answered cases" />
        <Stat label="Citations" value={formatPercent(run.metrics.citation_coverage)} hint="coverage" />
        <Stat label="Duration" value={formatMs(run.duration_ms)} hint={`${run.metrics.cases} cases`} tone="accent" />
      </div>
      <Card className="overflow-hidden">
        <div className="flex flex-wrap items-center justify-between gap-2 border-b px-5 py-4">
          <div>
            <h3 className="section-title">Case results</h3>
            <p className="mt-0.5 text-xs text-muted">
              Run <Mono>{run.id}</Mono> · {run.generate ? "retrieval + generation" : "retrieval only"}
            </p>
          </div>
          <StatusBadge status={run.status} />
        </div>
        <Table>
          <thead className="bg-raised/60 text-xs uppercase tracking-wide text-muted">
            <tr>
              <th className="px-4 py-2 font-medium">Question</th>
              <th className="px-4 py-2 font-medium">Hit</th>
              <th className="px-4 py-2 font-medium">RR</th>
              <th className="px-4 py-2 font-medium">Sources</th>
              <th className="px-4 py-2 font-medium">Grounded</th>
              <th className="px-4 py-2 font-medium">Latency</th>
            </tr>
          </thead>
          <tbody>
            {run.details.map((detail) => (
              <tr key={detail.case_id} className="border-t border-line/70 align-top">
                <td className="max-w-[24rem] px-4 py-3">
                  <span className="block text-sm">{detail.question}</span>
                  {detail.answer ? (
                    <span className="mt-1 block line-clamp-3 text-xs text-muted">{detail.answer}</span>
                  ) : null}
                  {detail.warnings.length ? (
                    <span className="mt-1 block text-xs text-warning">{detail.warnings[0]}</span>
                  ) : null}
                </td>
                <td className="px-4 py-3">
                  <StatusBadge status={detail.hit ? "Ready" : "Unindexed"} />
                </td>
                <td className="px-4 py-3 font-mono text-xs">{detail.reciprocal_rank.toFixed(4)}</td>
                <td className="px-4 py-3 font-mono text-xs">{detail.source_count}</td>
                <td className="px-4 py-3 font-mono text-xs">
                  {detail.grounded ? "yes" : "no"} ({detail.citation_count})
                </td>
                <td className="px-4 py-3 font-mono text-xs">{formatMs(detail.latency_ms)}</td>
              </tr>
            ))}
          </tbody>
        </Table>
      </Card>
      {run.details.some((detail) => detail.warnings.length) ? (
        <WarningList warnings={Array.from(new Set(run.details.flatMap((detail) => detail.warnings)))} />
      ) : null}
    </div>
  );
}
